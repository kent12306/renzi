// 获取计假方式描述文案（用于详情弹框只读展示）
function getCalcMethodText(leaveType) {
  if (leaveType === '补休假') return '按小时计算';
  if (leaveType === '疗养假') return '按分公司相关制度执行';
  if (leaveType === '产假（小产假）') return '按自然日计算（未满4个月流产15天，满4个月流产42天）';
  var isNatural = leaveCalcNatural[leaveType];
  return '按' + (isNatural ? '自然日' : '工作日') + '计算';
}
